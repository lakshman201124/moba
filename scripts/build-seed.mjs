#!/usr/bin/env node
// build-seed.mjs — Convert scripts/legacy/menu-data.js → supabase/seed.sql
// Run: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "fs";
import { randomUUID } from "crypto";
import { fileURLToPath } from "url";
import { dirname, join } from "path";
import vm from "vm";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const code = readFileSync(join(ROOT, "scripts/legacy/menu-data.js"), "utf8");

const ctx = { window: {} };
vm.runInNewContext(code, ctx);
const { categories, extras, dishes } = ctx.window.MOBA_MENU;

const esc = (s) =>
  s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`;
const uuid = () => randomUUID();
const lines = [];
const push = (s) => lines.push(s);

push("-- seed.sql — generated by scripts/build-seed.mjs");
push("-- Run once against an empty MOBA database after migrations.");
push("begin;");
push("");

// ── Addon ID map ──
const addonIds = {};
for (const e of extras) {
  addonIds[e.id] = uuid();
}

push("-- ── Add-ons ──");
for (let i = 0; i < extras.length; i++) {
  const e = extras[i];
  const id = addonIds[e.id];
  push(
    `insert into public.addons (id, name, price, diet, badge, sort_order) values (${esc(id)}, ${esc(e.name)}, ${e.price}, ${esc(e.diet)}, ${esc(e.badge || null)}, ${i});`
  );
}
push("");

// ── Choice group deduplication ──
// Key: JSON of { label, options (sorted), max }
const choiceGroupMap = new Map(); // key → { id, name, label, min, max, options: [{label, diet, price}] }
const NONVEG_RE = /chicken|fish|meat|prawn/i;
const VEG_RE = /tofu|paneer|veg|cauliflower|potato|mushroom/i;

function optionDiet(label) {
  if (NONVEG_RE.test(label)) return "nonveg";
  if (VEG_RE.test(label)) return "veg";
  return null;
}

function getChoiceGroupId(choose) {
  const label = choose.label;
  const max = choose.max || 1;
  const optLabels = choose.options.slice().sort();
  const key = JSON.stringify({ label, options: optLabels, max });

  if (choiceGroupMap.has(key)) return choiceGroupMap.get(key).id;

  const first3 = choose.options.slice(0, 3).join(", ");
  let baseName = `${label} — ${first3}${choose.options.length > 3 ? "…" : ""}`;
  // Make name unique
  const existingNames = new Set([...choiceGroupMap.values()].map((g) => g.name));
  let name = baseName;
  let suffix = 2;
  while (existingNames.has(name)) {
    name = `${baseName} #${suffix++}`;
  }

  const id = uuid();
  const options = choose.options.map((o, idx) => ({
    id: uuid(),
    label: o,
    diet: optionDiet(o),
    priceDelta: 0,
    sortOrder: idx,
  }));

  choiceGroupMap.set(key, { id, name, label, min: 1, max, options });
  return id;
}

// Pre-scan all dishes to build choice groups
for (const d of dishes) {
  if (d.choose) {
    for (const c of d.choose) {
      getChoiceGroupId(c);
    }
  }
}

push("-- ── Choice groups & options ──");
for (const g of choiceGroupMap.values()) {
  push(
    `insert into public.choice_groups (id, name, label, min_select, max_select) values (${esc(g.id)}, ${esc(g.name)}, ${esc(g.label)}, ${g.min}, ${g.max});`
  );
  for (const o of g.options) {
    push(
      `insert into public.choice_options (id, group_id, label, diet, price_delta, sort_order) values (${esc(o.id)}, ${esc(g.id)}, ${esc(o.label)}, ${esc(o.diet)}, ${o.priceDelta}, ${o.sortOrder});`
    );
  }
}
push("");

// ── Categories ──
const categoryIds = {};
const groupIds = {};

push("-- ── Categories ──");
for (let i = 0; i < categories.length; i++) {
  const c = categories[i];
  const id = uuid();
  categoryIds[c.id] = id;

  const notes = c.notes
    ? JSON.stringify(
        c.notes.map((n) => ({
          title: n.title,
          ko: n.ko || null,
          text: n.text || "",
          items: n.items || [],
        }))
      )
    : "[]";

  push(
    `insert into public.categories (id, slug, name, short_name, name_ko, blurb, art, notes, is_visible, sort_order) values (${esc(id)}, ${esc(c.id)}, ${esc(c.name)}, ${esc(c.short || null)}, ${esc(c.ko || null)}, ${esc(c.blurb || null)}, ${esc(c.art || "pot")}, ${esc(notes)}::jsonb, true, ${i});`
  );

  // Sub-sections (groups)
  if (c.groups) {
    for (let j = 0; j < c.groups.length; j++) {
      const g = c.groups[j];
      const gId = uuid();
      const gSlug = g[0];
      const gName = g[1];
      const gKo = g[2] || null;
      const gLede = g[3] || null;
      groupIds[`${c.id}:${gSlug}`] = gId;
      push(
        `insert into public.category_groups (id, category_id, slug, name, name_ko, lede, sort_order) values (${esc(gId)}, ${esc(id)}, ${esc(gSlug)}, ${esc(gName)}, ${esc(gKo)}, ${esc(gLede)}, ${j});`
      );
    }
  }

  // Category add-ons
  if (c.extras) {
    for (let j = 0; j < c.extras.length; j++) {
      const addonId = addonIds[c.extras[j]];
      if (addonId) {
        push(
          `insert into public.category_addons (category_id, addon_id, sort_order) values (${esc(id)}, ${esc(addonId)}, ${j});`
        );
      }
    }
  }
}
push("");

// ── Dishes ──
push("-- ── Dishes ──");
const dishCountByCategory = {};
for (const d of dishes) {
  if (!dishCountByCategory[d.category]) dishCountByCategory[d.category] = 0;
  const sortOrder = dishCountByCategory[d.category]++;
  const dishId = uuid();
  const catId = categoryIds[d.category];
  const grpId = d.group ? groupIds[`${d.category}:${d.group}`] || null : null;
  const lowestPrice =
    d.sizes && d.sizes.length > 0
      ? Math.min(...d.sizes.map((s) => s.price))
      : d.price;

  push(
    `insert into public.dishes (id, category_id, group_id, name, description, note, price, diet, spice, badge, is_available, is_visible, sort_order) values (${esc(dishId)}, ${esc(catId)}, ${esc(grpId)}, ${esc(d.name)}, ${esc(d.description || null)}, ${esc(d.note || null)}, ${lowestPrice}, ${esc(d.diet)}, ${d.spice || 0}, ${esc(d.badge || null)}, true, true, ${sortOrder});`
  );

  // Sizes
  if (d.sizes && d.sizes.length > 0) {
    for (let j = 0; j < d.sizes.length; j++) {
      const s = d.sizes[j];
      push(
        `insert into public.dish_sizes (id, dish_id, label, price, sort_order) values (${esc(uuid())}, ${esc(dishId)}, ${esc(s.label)}, ${s.price}, ${j});`
      );
    }
  }

  // Choice groups
  if (d.choose) {
    for (let j = 0; j < d.choose.length; j++) {
      const c = d.choose[j];
      const cgId = getChoiceGroupId(c);
      push(
        `insert into public.dish_choice_groups (dish_id, group_id, sort_order) values (${esc(dishId)}, ${esc(cgId)}, ${j});`
      );
    }
  }
}
push("");
push("commit;");
push("");

// Sanity counts
const catCount = categories.length;
const dishCount = dishes.length;
const addonCount = extras.length;
push(
  `-- Sanity: ${catCount} categories · ${dishCount} dishes · ${addonCount} add-ons`
);

const outPath = join(ROOT, "supabase/seed.sql");
writeFileSync(outPath, lines.join("\n") + "\n");
console.log(`✓ ${outPath}`);
console.log(
  `  ${catCount} categories · ${dishCount} dishes · ${addonCount} add-ons · ${choiceGroupMap.size} choice groups`
);
